"""Copy the event hall art into the prototype and write art/manifests.js.

Run from anywhere:  python3 build.py
- art/out/<x>/  -> prototype/art/<x>/  (deliverable PNGs + manifest, previews skipped)
- every PNG's size goes into manifest["sizes"], so the page can size sprites and strips
- Fright Fest pack prints and the approved Pack Room composites are copied READ-ONLY
  from the Pack Room design sources (never modified)
- screenshots of the live page go to art/current/
Checks: required files exist, hotspots sit inside the scene, the fold rule.
"""
import json
import os
import shutil
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.normpath(os.path.join(HERE, "..", "art", "out"))
DST = os.path.join(HERE, "art")
PACKROOM = "/Users/ozan/Documents/Projects/HallPass/artifacts/collectibles-redesign-src/art/out"
SHOTS = os.path.normpath(os.path.join(HERE, "..", "shots", "current"))

REQUIRED = ["cab-%s-%s.png" % (k, s) for k in ("lastbell", "shadowcore", "std", "mystery") for s in ("off", "on")] + [
    "pool-on.png", "tile-wall.png", "frame-board.png", "frame-quest.png", "frame-prize.png", "frame-paper.png"]

problems = []


def copy_concept(x):
    src = os.path.join(ART, x)
    man_path = os.path.join(src, "manifest.json")
    if not os.path.exists(man_path):
        print(f"[{x}] no manifest yet, the page uses placeholder boxes")
        return None
    with open(man_path) as f:
        man = json.load(f)
    out = os.path.join(DST, x)
    os.makedirs(out, exist_ok=True)
    sizes = {}
    for name in sorted(os.listdir(src)):
        if not name.endswith(".png") or ".preview." in name or name.startswith("composite"):
            continue
        shutil.copy2(os.path.join(src, name), os.path.join(out, name))
        with Image.open(os.path.join(src, name)) as im:
            sizes[name] = {"w": im.width, "h": im.height}
    man["sizes"] = sizes
    for r in REQUIRED:
        if r not in sizes:
            problems.append(f"[{x}] missing {r}")
    d = man.get("desk", {})
    for name, z in (d.get("zones") or {}).items():
        if isinstance(z, dict) and "x" in z:
            if z["x"] < 0 or z["y"] < 0 or z["x"] + z["w"] > 434 or z["y"] + z["h"] > 230:
                problems.append(f"[{x}] zone {name} leaves the scene: {z}")
    cab = d.get("cab", {})
    for i, s in enumerate(d.get("slots", [])):
        if s["y"] > 186:
            problems.append(f"[{x}] slot {i} starts below the fold row 186")
        b = cab.get("button") or {}
        if b.get("w") and s["y"] + b["y"] > 186:
            problems.append(f"[{x}] slot {i} PLAY strip starts at row {s['y'] + b['y']} (fold is 186)")
    for a in d.get("anims", []) + (man.get("phone", {}).get("anims") or []):
        if a["file"] not in sizes:
            problems.append(f"[{x}] anim file missing: {a['file']}")
    return man


def main():
    os.makedirs(DST, exist_ok=True)
    mans = {}
    for x in ("a", "b", "c"):
        m = copy_concept(x)
        if m:
            mans[x] = m
    # read-only references
    os.makedirs(os.path.join(DST, "packs"), exist_ok=True)
    for name in ("ff26-overall.png", "ff26-participation.png", "ff26-champion-last-bell.png",
                 "ff26-champion-shadow-core.png", "ff26-champion-survive-till-dawn.png"):
        shutil.copy2(os.path.join(PACKROOM, "packs", name), os.path.join(DST, "packs", name))
    os.makedirs(os.path.join(DST, "packroom"), exist_ok=True)
    for name in ("composite-desk-halloween.png", "composite-desk-normal.png", "composite-phone-halloween.png"):
        shutil.copy2(os.path.join(PACKROOM, "rooms", "a", name), os.path.join(DST, "packroom", name))
    if os.path.isdir(SHOTS):
        os.makedirs(os.path.join(DST, "current"), exist_ok=True)
        for name in os.listdir(SHOTS):
            if name.endswith(".png"):
                shutil.copy2(os.path.join(SHOTS, name), os.path.join(DST, "current", name))
    with open(os.path.join(DST, "manifests.js"), "w") as f:
        f.write("/* generated by build.py; do not edit */\nwindow.HALL_ART = ")
        json.dump(mans, f, separators=(",", ":"))
        f.write(";\n")
    print("concepts with art:", ", ".join(sorted(mans)) or "none")
    for p in problems:
        print("PROBLEM", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
