#!/usr/bin/env node
// Generates app/lib/static-games-manifest.ts — the set of game files baked into
// this deploy under public/games/<slug>/<relPath>.
//
// The game-serving route (app/game-html/[slug]/[[...path]]/route.ts) uses it to
// know whether a requested asset has a free static twin on Vercel's CDN before
// it decides to redirect there instead of proxying the bytes from Vercel Blob.
// Because it is generated at build time from the SAME public/games/ that ships,
// the "does a static twin exist" answer is always correct for the running
// deploy — a stale committed copy can only ever be regenerated identically.
//
// Runs as `prebuild` (and `predev`), before `next build` compiles the module, so
// the committed copy is only a convenience for typecheck/dev; the deploy always
// rebuilds it. Deterministic output (sorted, no timestamp) so re-running on
// unchanged games produces no diff.
//
// Usage: node scripts/build-games-manifest.mjs

import { writeFile } from "node:fs/promises";
import { existsSync, readdirSync, statSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(process.cwd());
const gamesDir = resolve(root, "public", "games");
const outPath = resolve(root, "app", "lib", "static-games-manifest.ts");

// Mirrors isSafeSegment in app/lib/game-html-blob.ts and the serving route's cap,
// so the manifest can never claim a path the route would refuse to serve anyway.
const SAFE_SEGMENT_RE = /^[A-Za-z0-9][A-Za-z0-9 ._-]*$/;
const MAX_PATH_SEGMENTS = 10;
const isSafeSegment = (s) => s.length <= 128 && SAFE_SEGMENT_RE.test(s);

const files = [];

if (existsSync(gamesDir)) {
  const slugs = readdirSync(gamesDir).filter((name) => {
    if (name.startsWith(".") || name.startsWith("_")) return false;
    return statSync(resolve(gamesDir, name)).isDirectory();
  });

  for (const slug of slugs) {
    const slugDir = resolve(gamesDir, slug);
    const stack = [slugDir];
    while (stack.length > 0) {
      const dir = stack.pop();
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = resolve(dir, entry.name);
        if (entry.isDirectory()) {
          stack.push(full);
          continue;
        }
        const rel = full.slice(slugDir.length + 1).split(/[/\\]/);
        // Keyed as "<slug>/<relPath>" — the same shape the route looks up.
        if (rel.length > MAX_PATH_SEGMENTS) continue;
        if (![slug, ...rel].every(isSafeSegment)) continue;
        files.push(`${slug}/${rel.join("/")}`);
      }
    }
  }
}

files.sort();

const out = `/**
 * Every game file baked into this deploy under \`public/games/<slug>/<relPath>\`,
 * keyed as \`<slug>/<relPath>\`. The game-serving route consults this set to know a
 * requested asset has a free static twin on the CDN before it redirects there
 * instead of proxying the bytes from Vercel Blob. See
 * {@link chooseGameSource} for how it is used.
 *
 * GENERATED by scripts/build-games-manifest.mjs (runs at prebuild/predev) — do
 * not edit by hand. Regenerated from public/games/ on every build, so it always
 * matches the static files that actually ship.
 */
export const STATIC_GAME_FILES: ReadonlySet<string> = new Set(${JSON.stringify(files, null, 2)});
`;

await writeFile(outPath, out, "utf8");
console.log(
  `[games-manifest] wrote ${outPath} — ${files.length} static game files`,
);
